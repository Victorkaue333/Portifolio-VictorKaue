i18n.use(LanguageDetector).use(initReactI18next).init({
  resources,
  supportedLngs: ['pt', 'en'],
  fallbackLng: 'pt',
  load: 'languageOnly',
  interpolation: {
    escapeValue: false,
  },
  detection: {
    order: ['localStorage', 'navigator', 'htmlTag'],
    lookupLocalStorage: 'portfolio-lang',
    caches: ['localStorage'],
    convertDetectedLanguage: (lng) => (lng?.toLowerCase().startsWith('en') ? 'en' : 'pt'),
  },
});

// Mantém <html lang> sincronizado com o idioma ativo (SEO + acessibilidade)
function syncHtmlLang(lng?: string) {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lng?.toLowerCase().startsWith('en') ? 'en' : 'pt-BR';
  }
}
syncHtmlLang(i18n.resolvedLanguage || i18n.language);
i18n.on('languageChanged', syncHtmlLang);

export default i18n;
